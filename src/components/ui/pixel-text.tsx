/** exact rendered width of a PixelText run — lets containers hug the
 * text instead of reserving worst-case boxes (2026-07-16 "간격오류") */
export function pixelTextWidth(text: string, cell = 1.3, led = false): number {
  const font = led ? G7 : G;
  let xOff = 0;
  for (const ch of text.toUpperCase()) {
    const glyph = font[ch];
    if (!glyph) continue;
    xOff += Math.max(...glyph.map((r) => r.length)) + 1;
  }
  return Math.max(xOff - 1, 1) * cell + 1;
}

export function PixelText({
  text,
  cell = 1.3,
  color,
  led = false,
}: {
  text: string;
  cell?: number;
  color: string;
  /** terminal-bitmap voice: the 5×7 board font in square pixels */
  led?: boolean;
}) {
  const font = led ? G7 : G;
  const rows = led ? 7 : 5;
  // settled THIN (2026-07-16, the BSOD memory-test reference — the
  // bold double-strike round read too wide/loud): single-pixel
  // strokes, 1-col gap, subtle
  const gap = 1;
  const extra = 0;
  let xOff = 0;
  const lit: { x: number; y: number }[] = [];
  for (const ch of text.toUpperCase()) {
    const glyph = font[ch];
    if (!glyph) continue;
    const width = Math.max(...glyph.map((r) => r.length));
    glyph.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) {
        if (row[x] === '#') lit.push({ x: xOff + x, y });
      }
    });
    xOff += width + extra + gap;
  }
  const cols = Math.max(xOff - gap + extra, 1);
  // +1pt canvas padding: the 1.04 pixel overlap pokes past the exact
  // grid box and SVG shaved the last row/col ("짤린거같이", 2026-07-16)
  const w = cols * cell + 1;
  const h = rows * cell + 1;

  if (!led) {
    const overlap = cell * 1.06;
    return (
      <Svg width={w} height={h}>
        {lit.map((r, i) => (
          <Rect
            key={i}
            x={r.x * cell}
            y={r.y * cell}
            width={overlap}
            height={overlap}
            fill={color}
          />
        ))}
      </Svg>
    );
  }

  // TERMINAL BITMAP: crisp single square pixels, no glow, no sockets
  return (
    <Svg width={w} height={h}>
      {lit.map((d, i) => (
        <Rect
          key={i}
          x={d.x * cell}
          y={d.y * cell}
          width={cell * 1.04}
          height={cell * 1.04}
          fill={color}
        />
      ))}
    </Svg>
  );
}

export default PixelText;
